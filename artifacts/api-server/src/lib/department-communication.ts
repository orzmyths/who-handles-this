function issueTopic(agency: Agency, text: string): string {
  // Select only curated phrases for this agency; never echo residents' free text,
  // extracted AI facts, addresses, notices, or another matched issue into drafts.
  return [...agency.includedExamples].sort((a, b) => b.length - a.length).find(example => text.toLowerCase().includes(example.toLowerCase()))
    ?? agency.includedExamples[0] ?? agency.scope;
}

// Keep this canonical prose curated in English. The resident email preview
// translates only channelNote, fallbackLabel, subject and body; recipients and
// evidence URLs must never be translated or generated by a language model.
export function communicationFor(agency: Agency, text: string, now = Date.now()): DepartmentCommunication | undefined {
  const contact = contacts[agency.id];
  if (!contact || !agencyById(agency.id) || isStale(agency, now)) return undefined;
  const { recipient, ...channel } = contact;
  const reviewed = Date.parse(contact.lastReviewed);
  if (!Number.isFinite(reviewed) || reviewed > now || now - reviewed > agency.reviewAfterDays * 86400000) {
    return {
      ...channel, sourceUrl: agency.officialUrl, lastReviewed: agency.lastReviewed,
      fallbackUrl: agency.officialUrl, fallbackLabel: "Open the department's official website",
      channelNote: "The contact source needs review. No email draft is available; confirm the current contact channel on the official website.",
    };
  }
  if (!recipient || !/^[A-Za-z0-9._+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$/.test(recipient)) return channel;
  const topic = issueTopic(agency, text);
  const appointment = agency.id === "sj-code-enforcement";
  const subject = appointment ? `Appointment request: ${topic}` : `Question about ${topic}`;
  const body = appointment
    ? `Hello ${agency.name},\n\nI would like to schedule an appointment to discuss ${topic} on private property in San José. Please let me know how to arrange an appointment with the appropriate Code Enforcement staff.\n\nI understand this email does not file a complaint or request an inspection. I will use your official service-request channel for that.\n\nThank you.`
    : `Hello ${agency.name},\n\nI am seeking guidance about ${topic} in Santa Clara County. Please let me know the appropriate next step and secure official channel for any required documents or identifying details.\n\nI understand this email does not make a payment, file an appeal, or submit an official case. I will follow the instructions and deadlines on my notice.\n\nThank you.`;
  return { ...channel, emailDraft: { recipient, subject, body } };
}